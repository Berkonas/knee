"""Build VALIDATION_REPORT.md for a study: per recording and per trial checks on the real data.

Usage: uv run python scripts/validation_report.py studies/<study> [out.md]
"""

import sys
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from trailbuddy.core import dataset, export, pipeline  # noqa: E402
from trailbuddy.core.analysis import load_result  # noqa: E402
from trailbuddy.core.project import Project  # noqa: E402

root = Path(sys.argv[1])
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("VALIDATION_REPORT.md")
pr = Project.load(root)
proc = {"backend": "rtmpose", "mode": "accurate", "stride": 1}
by_file = {}
for t in pr.trials:
    for v in t.videos:
        by_file[Path(v.path).name] = (t, v)
folder = Path(pr.trials[0].videos[0].path).parent
lines = ["# Validation report (real recordings)", "",
         f"Study: {pr.name}. Generated by `scripts/validation_report.py`. Every number below is computed from the data; nothing is estimated by hand.", "",
         "## Recordings", "", "| File | View | Device | Duration | fps | Trial | Pairing | Person detected | Pole coverage (L/R) | Status |",
         "|---|---|---|---|---|---|---|---|---|---|"]
for r in dataset.scan_folder(folder):
    if r.name not in by_file:
        lines.append(f"| {r.name} | – | {r.device} | {r.duration_s:.2f} s | {r.fps:.2f} | – | – | – | – | Excluded: {r.issue or 'not imported'} |")
        continue
    t, v = by_file[r.name]
    hit = pipeline.load_cached(root / "cache", v.path, proc)
    det = f"{100 * hit[2].get('detection_rate', 0):.0f}%" if hit else "–"
    cov = "/".join(f"{100 * hit[1][s].coverage():.0f}%" for s in ("left", "right")) if hit else "–"
    pair = (f"{t.sync.get('pair_status')} (r = {t.sync.get('pair_score'):.2f})" if t.sync.get("pair_score") is not None
            else ("single view: no audio-matching partner" if len(t.videos) < 2 else "manual"))
    status = "Passed" if len(t.videos) == 2 and t.sync.get("pair_status") == "confident" else (
        "Needs review" if t.sync.get("pair_status") == "review" else "Limited (single view)")
    lines.append(f"| {r.name} | {v.role} | {r.device} | {r.duration_s:.2f} s | {r.fps:.2f} | {t.id} | {pair} | {det} | {cov} | {status} |")
lines += ["", "## Trials", "", "| Trial | Views | Sync offset (method) | Window | Poles detected | Peak knee flexion | Export matches app |",
          "|---|---|---|---|---|---|---|"]
with tempfile.TemporaryDirectory() as td:
    for t in pr.trials:
        d = root / "trials" / t.id
        if not (d / "analysis.json").exists():
            lines.append(f"| {t.id} | – | – | – | – | – | not analysed |")
            continue
        res = load_result(d)
        files = export.export_trial(pr, t, res, td, proc, annotated_video=False)
        ts = pd.read_csv(Path(td) / t.participant_id / t.id / "timeseries.csv")
        same = np.allclose(ts.to_numpy(float), res.timeseries.to_numpy(float), rtol=1e-6, atol=1e-6, equal_nan=True)
        knee = res.metric("knee_flexion_peak")
        sync = (f"{t.sync['offset_s']:+.3f} s ({t.sync.get('method')})" if "offset_s" in t.sync and len(t.videos) == 2 else "–")
        win = f"{t.interval[0]:.2f}–{t.interval[1]:.2f} s" if t.interval else "–"
        pd_ = t.settings.get("poles_detected")
        lines.append(f"| {t.id} | {'+'.join(v.role for v in t.videos)} | {sync} | {win} | "
                     f"{'yes' if pd_ else ('no' if pd_ is False else '–')} | "
                     f"{'–' if knee is None or knee.value is None else f'{knee.value:.1f}°'} | {'yes' if same else 'NO'} |")
out.write_text("\n".join(lines) + "\n")
print(out)
